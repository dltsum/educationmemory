def main():
    random.seed(42)
    picks = random.sample(range(len(MATHDIAL)), len(STUDENTS))
    cases = []
    for s, di in zip(STUDENTS, picks):
        d = MATHDIAL[di]
        student_turns = []
        for c in d["conversation"].split("|EOM|"):
            if ":" in c:
                role, txt = c.split(":", 1)
                if role.strip().lower() != "teacher" and txt.strip():
                    student_turns.append(txt.strip())
        cases.append({
            "student": s,
            "dossier": render_dossier(s),
            "zpd_script": build_zpd(s),
            "mathdial": {"qid": d["qid"], "question": d["question"],
                         "incorrect_solution": d["student_incorrect_solution"],
                         "student_turns": student_turns[:6]},
            "probes": build_probes(s),
            "exams": EXAMS.get(s["id"], {"src": "", "qs": []}),
        })
    out = os.path.join(ROOT, "student_cases.json")
    json.dump(cases, open(out, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(f"saved {len(cases)} cases -> {out}")
    print("dossier lengths:", [len(c["dossier"]) for c in cases])

if __name__ == "__main__":
    main()
