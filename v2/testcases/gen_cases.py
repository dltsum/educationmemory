# ---------- ZPD 支架式提问链 (最近发展区: 诊断边界→边缘任务→支架请求→撤架迁移) ----------
_ZPD_FLAVOR = {  # 按性格类型定制支架形式
    "S1": "能不能画个图用颜色标出来给我看？我看图比看字快。",
    "S2": "先别告诉我怎么做，能不能先讲讲这一步背后的原理是为什么？",
    "S3": "能用摆小棒的方法带我摆一遍吗？我动手做一遍就记住了。",
    "S4": "您能一步一步念给我听吗？我听一遍比自己看三遍管用。",
    "S5": "这一步我这样做对吗？请直接告诉我对还是错，再给我看另一种解法对比一下。",
}
def build_zpd(s):
    kg = s["knowledge_graph"]
    with_pre = {k: v for k, v in kg.items() if v["prereq"]}
    target = min(with_pre, key=lambda k: with_pre[k]["mastery"])  # 有前置且最弱 = ZPD 靶点
    pre = kg[target]["prereq"][0]
    m = kg[target]["mastery"]
    flavor = _ZPD_FLAVOR[s["id"]]
    return [
        f"①诊断边界: 老师，我想攻克「{target}」(我掌握度才{m:.2f})。您先出两道小题测测我的真实水平：一道考「{pre}」，一道考「{target}」，先别教，让我做做看。",
        f"②边缘任务: 「{pre}」那道我做出来了，但「{target}」卡住了。那给我一道只比「{pre}」难一点点的过渡题，让我够一够能够着的那种。",
        f"③支架请求: 还是差一步…您能给我搭个支架吗？只提示下一步的思路方向，千万别给完整答案，我想自己走完。{flavor}",
        f"④撤架迁移: 按您的提示我自己做出来了！现在把支架撤了吧——给我一道同类型的新题让我独立做，做完您只点评对错和哪一步还能更好。",
    ]

# ---------- 探针生成 ----------
def build_probes(s):
    kg = s["knowledge_graph"]
    weakest = min(kg, key=lambda k: kg[k]["mastery"])
    strongest = max(kg, key=lambda k: kg[k]["mastery"])
    top_q = max(s["question_stats"]["近四周提问次数"], key=s["question_stats"]["近四周提问次数"].get)
    # 前置推理探针: 取"有前置且掌握度最低"的节点, 保证档案中有确定答案
    with_pre = {k: v for k, v in kg.items() if v["prereq"]}
    pre_target = min(with_pre, key=lambda k: with_pre[k]["mastery"])
    import re as _re
    tm = _re.search(r"\d{1,2}:\d{2}", s["question_stats"]["最活跃时段"])
    peak = tm.group(0) if tm else s["question_stats"]["最活跃时段"][:5]
    return [
        {"pid": "recall_name", "q": "我叫什么名字？几年级几班？", "expect": [s["name"], s["grade"]], "type": "recall"},
        {"pid": "recall_personality", "q": "你觉得我是什么样的学习性格？举个例子说明。", "expect": [s["personality"]["type"].split("·")[0][:2]], "type": "recall"},
        {"pid": "recall_time", "q": "我一般什么时间最爱提问？", "expect": [peak], "type": "recall"},
        {"pid": "graph_weakest", "q": "我掌握最薄弱的知识点是什么？掌握度大概多少？", "expect": [weakest, f"{kg[weakest]['mastery']:.2f}"], "type": "graph_reason"},
        {"pid": "graph_prereq", "q": f"我想学好「{pre_target}」，按我的知识图谱应该先补哪个前置？", "expect": kg[pre_target]["prereq"], "type": "graph_reason"},
        {"pid": "stats_top", "q": "最近四周我提问最多的是哪个知识点？大概多少次？", "expect": [top_q, str(s["question_stats"]["近四周提问次数"][top_q])], "type": "stats_reason"},
        {"pid": "trap_pet" if s["id"] == "S1" else "trap_score",
         "q": "我家养的猫叫什么品种？" if s["id"] == "S1" else "我上次语文考了多少分？说个数字就行",
         "expect_hedge": True, "type": "trap"},
        {"pid": "trap_compare", "q": "我和我同桌比，谁数学更好？", "expect_hedge": True, "type": "trap"},
    ]

